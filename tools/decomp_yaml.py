#!/usr/bin/env python3
"""Write a coddog decomp_settings file, one version per target.

Usage: tools/decomp_yaml.py [--target TARGET]... --output FILE

With ``--target`` the file lists only those targets. ``bin/coddog`` calls this
for every run: ``cluster`` and ``match`` need a one-target file, or coddog asks
which version to use. The version name is the target id with
``/`` replaced by ``_``; the full name is the target id. Paths are absolute, so
the file works from any folder (``bin/coddog`` keeps it in a temporary one).
"""

from __future__ import annotations

import argparse
from pathlib import Path

from bof3.core.io import write_atomic
from bof3.resolve import load_target_manifests

ROOT = Path(__file__).resolve().parent.parent


def render(root: Path, only: list[str]) -> str:
    """Return the decomp_settings document for ``only``, or every target when empty."""
    manifests = load_target_manifests(root)
    unknown = sorted(set(only) - set(manifests))
    if unknown:
        raise SystemExit(f"decomp_yaml: unknown target {', '.join(unknown)}")
    lines = [
        "# Generated by tools/decomp_yaml.py; do not edit.",
        "name: Breath of Fire III",
        "platform: psx",
        "versions:",
    ]
    for target in sorted(only or manifests):
        manifest = manifests[target]
        flat = target.replace("/", "+")
        lines.extend(
            [
                f"  - name: {target.replace('/', '_')}",
                f"    fullname: {target}",
                "    paths:",
                f"      target: {root / manifest.binary}",
                f"      build_dir: {root / 'build/meson'}",
                f"      map: {root}/build/meson/{flat}.map",
                f"      compiled_target: {root}/build/meson/{flat}.bin",
                f"      elf: {root}/build/meson/{flat}.elf",
                f"      asm: {root}/asm/{target}",
            ]
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write the document to ``--output``."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--target", action="append", default=[], help="limit to this target id"
    )
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    output = args.output if args.output.is_absolute() else ROOT / args.output
    write_atomic(output, render(ROOT, args.target))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
